package com.insideinvoice.admin.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.List;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class AdminStatsResponse {

    private long totalUsers;
    private long totalBusinesses;
    private long totalInvoices;
    private long totalCustomers;
    private long totalProducts;
    private long activeUsersLast30Days;
    private long invoicesLast30Days;
    /**
     * Per-day platform activity for the 30 days ending today (contiguous, empty
     * days included). Active user = a user who generated at least one invoice
     * that day. Rendered as the dashboard's "Active Users"/"Invoices Generated"
     * last-30-days charts.
     */
    private List<DailyActivity> dailyActivity;
    /**
     * New platform users per month, last 6 months (contiguous, empty months=0).
     */
    private List<MonthlyCount> newUsersByMonth;
    /**
     * The CALLING admin's own business invoices per month, last 12 months —
     * "someone bought (the product), I generate the invoice" operator view.
     */
    private List<MonthlyCount> ownInvoicesByMonth;
    private List<UserSummary> recentUsers;

    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class UserSummary {
        private Long id;
        private String name;
        private String email;
        private String role;
        private Long businessId;
        private String createdAt;
    }

    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class DailyActivity {
        /** ISO date, e.g. 2026-10-19. */
        private String date;
        /** Invoices generated by ALL users on this day. */
        private long invoices;
        /** Distinct users who generated at least one invoice on this day. */
        private long activeUsers;
    }

    @Getter
    @Setter
    @NoArgsConstructor
    @AllArgsConstructor
    @Builder
    public static class MonthlyCount {
        /** Month key "YYYY-MM". */
        private String month;
        private long count;
    }
}
